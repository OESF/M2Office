/**
 * いまの時刻と曜日から選ぶ、時候の一言。
 *
 * @param now いまの時刻。試験のために渡せるようにしてある
 *
 * @remarks
 * **祝日は判定しない。** 日本の祝日は暦を持たないと分からず、年ごとに変わる。
 * 間違えて「休日ですね」と言うくらいなら言わない（不変則 I-6 と同じ考え方）。
 * 土曜・日曜は曜日から確かに分かるので、時刻より優先する。
 */
export function timeGreeting(now = new Date()): string {
  const day = now.getDay();
  if (day === 0 || day === 6) return '休日にお疲れさまです';
  const h = now.getHours();
  if (h >= 5 && h < 11) return 'おはようございます';
  if (h >= 11 && h < 18) return 'こんにちは';
  if (h >= 18 && h < 22) return 'お疲れさまです';
  return '遅くまでお疲れさまです';
}
