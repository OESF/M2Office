/**
 * @file レポートの表の中のリンクを外す（競合の分析。仕様書 第36.11節）。
 *
 * 2026-10-04 に三浦さんが、自社との違いの表で会社名がすべてリンクになっていて見づらいと指摘し、リンクマークに改めた。
 * その後、表の中のリンクはどれも同じ先（相手のトップのページ）で意味が無いとして、表の中のリンクは外すことにした。出典は一覧の「データ数」から 1 社ずつ見られる。
 * 表の外のリンクはそのまま。
 */

/**
 * 表の行（`|` から始まる行）の `[名前](URL)` を `名前` にする。`[出典](URL)`・`[🔗](URL)` は消す。
 *
 * @param text レポートの Markdown
 */
export function stripTableLinks(text: string): string {
  return text.split('\n').map((line) => (line.trimStart().startsWith('|')
    ? line.replace(/\s*[（(]?\[(出典|🔗)\]\([^)\s]+\)[）)]?/g, '').replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, '$1')
    : line)).join('\n');
}
