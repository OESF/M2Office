/**
 * @file 音声の聞き取りの文字を整える（仕様書 第10.5.2節「聞き取りの文字」。第 0.606.3 版）。
 *
 * 音声の相手（Gemini Live）は、聞き取りの言語を指定できず、音から推し量る。そのため日本語の会話でも、
 * 単語の間に空白が入ったり（「今週 の 予定 を」）、短い声や雑音がハングルの文字（「어?」）になったりする（2026-11-17 に三浦さんが指摘）。
 * 字幕と会話の記録（秘書が学ぶもと・入力欄の ↑ で呼び戻すもと）に、そのまま残さないため、文字の形だけを見て整える。
 * 言葉の意味は読まない（第49.4節「形を読む」）。
 */

// @wordlist 形を読む（第49.4節）
/** 日本語の文字（漢字・ひらがな・カタカナ・長音と繰り返しの記号・和文の約物）。この前後の空白を詰める。 */
const JA = String.raw`\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}ー々〆、。！？「」『』（）・…`;
// @wordlist 形を読む（第49.4節）
/** 日本語の文字に接する空白（半角・全角）。 */
const SPACE_BY_JA = new RegExp(String.raw`(?<=[${JA}])[ 　]+|[ 　]+(?=[${JA}])`, 'gu');
// @wordlist 形を読む（第49.4節）
/** ハングルの文字の続き（後ろに付いた句読点と空白を含む）。日本語の会話の聞き違えとして外す。 */
const HANGUL_RUN = /[\p{Script=Hangul}]+[?？!！。、.,]*[ 　]*/gu;

/**
 * 聞き取りの文字を整える。日本語の文字に接する空白を詰め、ハングルの文字を外す。
 *
 * @remarks
 * 断片ごとにも、1 回の発話をまとめた文にも使える（断片の境目の空白は、まとめた文で詰まる）。
 * 英字どうしの間の空白（「Google Drive」）は残す。日本語のほかの言語で話す人は想定しない（M2Office の画面と秘書は日本語）。
 *
 * @param text 聞き取りの文字
 * @returns 整えた文字（外した結果が空なら空）
 */
export function tidyTranscript(text: string): string {
  return text.replace(HANGUL_RUN, '').replace(SPACE_BY_JA, '');
}
